// @vitest-environment jsdom
import { QueryClient, QueryClientProvider } from '@tanstack/react-query'
import { render, screen } from '@testing-library/react'
import { describe, expect, it, vi } from 'vitest'
import App from './App'

describe('transparency review office', () => {
  it('loads transparency reviews from the Java API', async () => {
    vi.stubGlobal('fetch', vi.fn().mockResolvedValue({
      ok: true,
      json: async () => [{ id: 1, title: 'European generative-content marking review', owner: 'European AI Innovation Team', status: 'Review', priority: 'High' }],
    }))
    const client = new QueryClient({ defaultOptions: { queries: { retry: false } } })
    render(<QueryClientProvider client={client}><App /></QueryClientProvider>)
    expect(await screen.findByText('European generative-content marking review')).toBeTruthy()
    expect(screen.getByRole('heading', { name: 'AI Transparency Disclosure Office' })).toBeTruthy()
  })
})
